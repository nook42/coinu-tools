const CATALOGS = { en, ja, zh };

export function hasTranslation(lang, key) {
  return Object.hasOwn(CATALOGS, lang) && Object.hasOwn(CATALOGS[lang], key);
}

let warnedMissing = new Set();

export function t(lang) {
  const primary = Object.hasOwn(CATALOGS, lang) ? CATALOGS[lang] : en;
  return (key, params) => {
    let tpl = primary[key];
    if (tpl === undefined) tpl = en[key];
    if (tpl === undefined) {
      if (!warnedMissing.has(key)) { warnedMissing.add(key); try { console.warn(`i18n missing key: ${key}`); } catch {} }
      return key;
    }
    return tpl.replace(/\{(\w+)\}/g, (m, p) => (params && Object.prototype.hasOwnProperty.call(params, p) ? String(params[p]) : '-'));
  };
}

export function pickLang(saved) {
  if (SUPPORTED_LANGS.includes(saved)) return saved;
  try {
    const nav = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'en').toLowerCase();
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('zh')) return 'zh';
  } catch { /* noop */ }
  return 'en';
}
